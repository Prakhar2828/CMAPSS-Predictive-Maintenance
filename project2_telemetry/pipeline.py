"""Operational telemetry pipeline for the C-MAPSS dashboard.

This module represents the hot path: lightweight ingestion, schema validation,
anomaly rules, and a dashboard-ready cache. It intentionally does not train ML
models; it consumes the outputs generated by project1_ml/train_uq.py.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

ROOT_DIR = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT_DIR / "data"
OUT_DIR = Path(__file__).resolve().parent

COLUMNS = ["unit_id", "cycle", "setting1", "setting2", "setting3"] + [f"s{i}" for i in range(1, 22)]
MONITORED_SENSORS = ["s2", "s3", "s4", "s7", "s11", "s12", "s15", "s17", "s20", "s21"]


class TelemetryPipeline:
    """Small data-engineering pipeline that turns raw test telemetry into an operational cache."""

    def __init__(self, raw_data_file: Path):
        self.raw_file = raw_data_file

    def ingest_raw_stream(self) -> pd.DataFrame:
        if not self.raw_file.exists():
            raise FileNotFoundError(f"Missing raw telemetry file: {self.raw_file}")
        df = pd.read_csv(self.raw_file, sep=r"\s+", header=None, names=COLUMNS)
        return df.sort_values(["unit_id", "cycle"]).reset_index(drop=True)

    def validate_schema(self, df: pd.DataFrame) -> None:
        missing = set(COLUMNS) - set(df.columns)
        if missing:
            raise ValueError(f"Telemetry schema missing columns: {sorted(missing)}")
        if df[["unit_id", "cycle"]].isna().any().any():
            raise ValueError("Telemetry data has null unit_id or cycle values.")
        if (df["cycle"] <= 0).any():
            raise ValueError("Telemetry data contains non-positive cycle values.")

    def apply_operational_flags(self, df: pd.DataFrame) -> pd.DataFrame:
        """Flag sensor outliers and fast sensor shifts using simple edge rules."""
        df = df.copy()
        df["anomaly_flag"] = 0
        df["anomaly_score"] = 0.0
        df["anomaly_reason"] = "normal"

        for sensor in MONITORED_SENSORS:
            mean = df[sensor].mean()
            std = df[sensor].std(ddof=0)
            if std == 0 or np.isnan(std):
                continue

            z_col = f"{sensor}_zscore"
            df[z_col] = (df[sensor] - mean) / std
            extreme_mask = df[z_col].abs() > 3.0
            df.loc[extreme_mask, "anomaly_flag"] = 1
            df.loc[extreme_mask, "anomaly_reason"] = np.where(
                df.loc[extreme_mask, "anomaly_reason"] == "normal",
                f"{sensor} extreme z-score",
                df.loc[extreme_mask, "anomaly_reason"] + f"; {sensor} extreme z-score",
            )
            df["anomaly_score"] = np.maximum(df["anomaly_score"], df[z_col].abs())

            delta = df.groupby("unit_id")[sensor].diff().fillna(0)
            delta_std = delta.std(ddof=0)
            if delta_std and not np.isnan(delta_std):
                jump_mask = delta.abs() > 3.5 * delta_std
                df.loc[jump_mask, "anomaly_flag"] = 1
                df.loc[jump_mask, "anomaly_reason"] = np.where(
                    df.loc[jump_mask, "anomaly_reason"] == "normal",
                    f"{sensor} sudden shift",
                    df.loc[jump_mask, "anomaly_reason"] + f"; {sensor} sudden shift",
                )

        # Fleet/engine age context for the UI.
        max_cycle = df.groupby("unit_id")["cycle"].transform("max")
        df["cycle_norm"] = df["cycle"] / max_cycle
        return df

    def run_pipeline(self, output_path: Path) -> pd.DataFrame:
        print("Executing ingestion and anomaly pipeline...")
        df = self.ingest_raw_stream()
        self.validate_schema(df)
        df = self.apply_operational_flags(df)
        df.to_csv(output_path, index=False)
        print(f"Cleaned telemetry data saved to {output_path}")
        print(f"Rows processed: {len(df):,} | Anomaly rows: {int(df['anomaly_flag'].sum()):,}")
        return df


def main() -> None:
    pipeline = TelemetryPipeline(DATA_DIR / "test_FD001.txt")
    pipeline.run_pipeline(OUT_DIR / "cleaned_telemetry.csv")


if __name__ == "__main__":
    main()
